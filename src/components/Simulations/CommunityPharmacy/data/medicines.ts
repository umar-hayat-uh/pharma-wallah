export const MEDICINE_INDEX: Record<string, Medicine> = {};
MEDICINES.forEach((m) => {
  MEDICINE_INDEX[m.id] = m;
});

export { MEDICINES };

export function medicine(id: string): Medicine | undefined {
  return MEDICINE_INDEX[id];
}

/** Display name used everywhere a product is named on screen. */
export function medicineLabel(m: Medicine): string {
  return `${m.brand} (${m.generic}) ${m.strength} ${m.form}`;
}

export function medicinesByCategory(category: string): Medicine[] {
  return MEDICINES.filter((m) => m.category === category);
}

/**
 * Free-text search across brand, generic and category.
 *
 * Deliberately simple and case-insensitive — the shelf search is a convenience
 * for finding a bay, not a clinical lookup.
 */
export function searchMedicines(query: string, pool?: Medicine[]): Medicine[] {
  const list = pool || MEDICINES;
  const q = query.trim().toLowerCase();
  if (!q) return list;
  return list.filter(
    (m) =>
      m.brand.toLowerCase().includes(q) ||
      m.generic.toLowerCase().includes(q) ||
      m.category.includes(q) ||
      m.strength.toLowerCase().includes(q),
  );
}

/** Every counselling topic, in the fixed order, for a given medicine. */
export function counsellingFor(m: Medicine, topic: CounsellingTopic): CounsellingContent {
  return m.counselling[topic];
}
