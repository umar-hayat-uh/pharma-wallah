#!/usr/bin/env node
/**
 * Generates the Windows desktop app's calculator route tree.
 *
 * Exactly the same trick as scripts/generate-mobile-routes.mjs, and for the
 * same reason: the calculators live in
 * `src/app/(site)/calculation-tools/(tools)/<slug>/` and are the single source
 * of truth. Copying them into `desktop/` would drift the moment a tool is
 * edited, so this emits a one-line re-export page per tool and all three
 * targets (web, Android, Windows) compile the same file.
 *
 * Run automatically by `npm run desktop:build` / `npm run tauri:build`.
 * Idempotent: routes for tools that no longer exist are removed, so deleting a
 * calculator cannot leave a dead page inside the installer.
 *
 * NOTE: only the page component is re-exported, so nothing in
 * `src/app/(site)/**` layouts reaches the desktop app (MEMORY gotcha 28). The
 * desktop chrome lives in `desktop/app/calculation-tools/layout.tsx`.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = join(repoRoot, "src/app/(site)/calculation-tools/(tools)");
const routesDir = join(repoRoot, "desktop/app/calculation-tools");
const generatedDir = join(repoRoot, "desktop/app/_generated");

const slugs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((slug) => existsSync(join(toolsDir, slug, "page.tsx")))
  .sort();

if (slugs.length === 0) {
  console.error("[desktop] No calculator directories found — refusing to emit an empty app.");
  process.exit(1);
}

// Drop every previously generated slug directory. The hand-written files in
// this directory (page.tsx, layout.tsx) are not directories, so they survive.
if (existsSync(routesDir)) {
  for (const entry of readdirSync(routesDir, { withFileTypes: true })) {
    if (entry.isDirectory()) rmSync(join(routesDir, entry.name), { recursive: true, force: true });
  }
}

for (const slug of slugs) {
  const dir = join(routesDir, slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "page.tsx"),
    `// GENERATED by scripts/generate-desktop-routes.mjs — do not edit.\n` +
      `// Source: src/app/(site)/calculation-tools/(tools)/${slug}/page.tsx\n` +
      `export { default } from "@/app/(site)/calculation-tools/(tools)/${slug}/page";\n`,
  );
}

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  join(generatedDir, "tool-slugs.ts"),
  `// GENERATED by scripts/generate-desktop-routes.mjs — do not edit.\n` +
    `// Every calculator directory that ships in the Windows desktop app.\n` +
    `export const TOOL_SLUGS = [\n` +
    slugs.map((slug) => `  ${JSON.stringify(slug)},\n`).join("") +
    `] as const;\n`,
);

console.log(`[desktop] Generated ${slugs.length} calculator routes.`);
