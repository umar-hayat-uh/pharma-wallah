#!/usr/bin/env node
/**
 * Generates the Android app's route tree from the calculator directories.
 *
 * The 89 calculators live in `src/app/(site)/calculation-tools/(tools)/<slug>/`
 * and are the single source of truth. Rather than copying them into the mobile
 * project (which would drift the moment a tool is edited), this script emits a
 * one-line re-export page per tool, so both builds compile the same file.
 *
 * Run automatically by `npm run mobile:build`. Safe and idempotent: it removes
 * generated routes for tools that no longer exist, so deleting a calculator
 * does not leave a dead page in the APK.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = join(repoRoot, "src/app/(site)/calculation-tools/(tools)");
const routesDir = join(repoRoot, "mobile/app/calculation-tools");
const generatedDir = join(repoRoot, "mobile/app/_generated");

const slugs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((slug) => existsSync(join(toolsDir, slug, "page.tsx")))
  .sort();

if (slugs.length === 0) {
  console.error("[mobile] No calculator directories found — refusing to emit an empty app.");
  process.exit(1);
}

// Drop every previously generated slug directory. The hub page at
// mobile/app/calculation-tools/page.tsx is hand-written, so keep it.
if (existsSync(routesDir)) {
  for (const entry of readdirSync(routesDir, { withFileTypes: true })) {
    if (entry.isDirectory()) rmSync(join(routesDir, entry.name), { recursive: true, force: true });
  }
}

for (const slug of slugs) {
  const dir = join(routesDir, slug);
  mkdirSync(dir, { recursive: true });
  // A page module's default export is the page component. Re-exporting the
  // real tool page keeps the calculator itself in exactly one place.
  writeFileSync(
    join(dir, "page.tsx"),
    `// GENERATED by scripts/generate-mobile-routes.mjs — do not edit.\n` +
      `// Source: src/app/(site)/calculation-tools/(tools)/${slug}/page.tsx\n` +
      `export { default } from "@/app/(site)/calculation-tools/(tools)/${slug}/page";\n`,
  );
}

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  join(generatedDir, "tool-slugs.ts"),
  `// GENERATED by scripts/generate-mobile-routes.mjs — do not edit.\n` +
    `// Every calculator directory that ships in the Android app.\n` +
    `export const TOOL_SLUGS = [\n` +
    slugs.map((slug) => `  ${JSON.stringify(slug)},\n`).join("") +
    `] as const;\n`,
);

console.log(`[mobile] Generated ${slugs.length} calculator routes.`);
