#!/usr/bin/env python3
"""
Builds docs/ADSENSE_ROUTE_INVENTORY.md from two crawls made by scripts/audit-crawl.py:
one of production (before) and one of a local `next start` of the working tree (after).

  python3 scripts/route-inventory.py live.json local.json > docs/ADSENSE_ROUTE_INVENTORY.md

Page type comes from the path. "Server text" is the number of words in the server-rendered
HTML (navigation and footer included, so ~150 is an empty page) — what a crawler sees before
any JavaScript runs. Interaction was not exercised by the crawl; see the method notes.
"""
import json, sys, collections, datetime

live = json.load(open(sys.argv[1]))
local = json.load(open(sys.argv[2]))
L = {p["path"]: p for p in live["pages"]}
N = {p["path"]: p for p in local["pages"]}
paths = sorted(set(L) | set(N), key=lambda p: (p.split("/")[1:2], p))
paths = [p for p in paths if not p.startswith("/images/")]

def ptype(p):
    rules = [
        ("/calculation-tools/how-to-use", "Guide (calculators)"), ("/calculation-tools/", "Calculator"),
        ("/calculation-tools", "Calculator hub"), ("/guides/", "Guide"), ("/guides", "Guide index"),
        ("/courses/", "Course"), ("/courses", "Course hub"), ("/mcqs-bank", "MCQ bank"),
        ("/spotting", "Spotting"), ("/virtual-labs", "Virtual lab"), ("/clinical", "Clinical"),
        ("/battle-royale", "Event"), ("/tournament", "Event (ended)"), ("/community", "Community"),
        ("/encyclopedia", "Drug encyclopedia"), ("/dashboard", "Account"),
    ]
    for prefix, t in rules:
        if p == prefix or p.startswith(prefix):
            return t
    tools = {"/molecular-lab", "/pharmacy-counter", "/antibiogram-simulator", "/adr-detective",
             "/drug-finder", "/ai-guide", "/prescription-reader", "/flash-cards"}
    if p in tools:
        return "Interactive tool"
    if p in {"/about-us", "/contact", "/careers", "/faqs", "/privacy", "/terms", "/editorial-policy", "/download"}:
        return "Trust / info"
    return "Home" if p == "/" else "Other"

def indexable(p):
    return p and p["status"] == 200 and not (p.get("robots") and "noindex" in p["robots"])

def defects(path, a, b):
    out = []
    pg = b or a
    if a and a.get("softRedirect"):
        out.append("live: client redirect served as 200 (closed event)")
    if b is None and a is not None:
        out.append("not reached locally (removed from sitemap/links)")
    if pg and pg["status"] == 200 and indexable(pg) and pg["words"] < 230 and ptype(path) not in ("Account",):
        out.append(f"little server-rendered text ({pg['words']} words incl. nav) — content renders client-side")
    if pg and pg.get("canonical") and pg["canonical"].rstrip("/") != ("https://www.pharmawallah.com" + (path if path != "/" else "")).rstrip("/"):
        out.append("canonicalises to " + pg["canonical"].replace("https://www.pharmawallah.com", ""))
    if a and b and a["status"] == 200 and b["status"] == 200 and a.get("title") != b.get("title"):
        out.append("title changed")
    return "; ".join(out) or "—"

print("# AdSense route inventory\n")
print(f"> Generated by `scripts/route-inventory.py` on {datetime.date.today()} from two crawls: **live** = "
      "https://www.pharmawallah.com before this remediation, **local** = `next start` of the working tree after it. "
      "Both start at `/` and every sitemap URL and follow internal links. Images and `/api/*` are excluded.\n")
c_live = collections.Counter(p["status"] for p in live["pages"] if not p["path"].startswith("/images/"))
c_loc = collections.Counter(p["status"] for p in local["pages"] if not p["path"].startswith("/images/"))
print("| Measure | Live (before) | Local (after) |\n| --- | --- | --- |")
print(f"| Routes reached | {sum(c_live.values())} | {sum(c_loc.values())} |")
print(f"| HTTP 200 | {c_live[200]} | {c_loc[200]} |")
print(f"| Sitemap URLs | {len(live['sitemap'])} | {len(local['sitemap'])} |")
print(f"| Indexable (200, no noindex) | {sum(1 for p in live['pages'] if indexable(p) and not p['path'].startswith('/images/'))} | {sum(1 for p in local['pages'] if indexable(p) and not p['path'].startswith('/images/'))} |")
print(f"| Soft redirects (200 + client redirect) | {sum(1 for p in live['pages'] if p['softRedirect'])} | {sum(1 for p in local['pages'] if p['softRedirect'])} |")
print(f"| Pages with JSON-LD | {sum(1 for p in live['pages'] if p['ldjson'])} | {sum(1 for p in local['pages'] if p['ldjson'])} |")
print()
by_type = collections.Counter(ptype(p) for p in paths)
print("**Routes by type:** " + ", ".join(f"{t} {n}" for t, n in sorted(by_type.items(), key=lambda x: -x[1])) + "\n")
print("| Route | Type | Live | Local | Index | Sitemap | Server text | JSON-LD | Title (local) | Notes |")
print("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for path in paths:
    a, b = L.get(path), N.get(path)
    pg = b or a
    idx = "yes" if indexable(pg) else ("noindex" if pg and pg["status"] == 200 else "—")
    sm = "yes" if (b or a).get("inSitemap") else "—"
    title = (pg.get("title") or "").replace("|", "·")[:70]
    print(f"| `{path}` | {ptype(path)} | {a['status'] if a else '—'} | {b['status'] if b else '—'} | {idx} | {sm} | "
          f"{pg['words'] if pg else ''} | {pg['ldjson'] if pg else ''} | {title} | {defects(path, a, b)} |")
print("""
## Method notes and limits

- **Status, title, canonical, robots, server text and JSON-LD are measured.** The crawl does not
  click anything: whether each page's *main interaction works* was verified only for the pages
  listed in `ADSENSE_FULL_AUDIT_REPORT.md` §5 (headless Chrome, desktop and phone), not for every row.
- "Little server-rendered text" is a crawler's-eye measurement, not a verdict: simulations,
  community and clinical search shells are interactive tools whose content appears after
  hydration. Google renders JavaScript; an AdSense reviewer uses a browser. Listed as POTENTIAL risk.
- `/dashboard` 307 → `/signin` is expected (sign-in required).
- The live crawl's one other non-200 (`/calculation-tools/volume-distribution-calculator`, status 0)
  was a client-side timeout; it returned 200 twice on retry.
- Routes behind sign-in, admin routes and query-string variants were not crawled.
- Unknown slugs under dynamic routes (`/guides/x`, `/courses/x`) answer **200 with the not-found UI
  and `noindex`** — a soft 404 caused by the root `loading.tsx` (MEMORY gotcha 183). Not indexed,
  so low impact; recorded in `TECHNICAL_SEO_AUDIT.md`.
""")
