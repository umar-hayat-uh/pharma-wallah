#!/usr/bin/env python3
"""
Writes AUDIT.md from a crawl made by scripts/audit-crawl.py (and, optionally, a rendered
word-count file from a headless browser).

  python3 scripts/audit-report.py crawl.json [rendered.json] > AUDIT.md

"Unique words" = words in the page's <main> after removing every text line that appears on
more than BOILERPLATE_PAGES pages (navigation, disclaimers, footers inside <main>, the
calculator provenance line, …). It is a crawler's-eye measure of what this page says that
others do not — the thing "low value content" is about.
"""
import json, sys, collections, re

BOILERPLATE_PAGES = 8
THIN = 300
DEFAULT_TITLE = "PharmaWallah — Pharm-D study tools, calculators and lessons"

crawl = json.load(open(sys.argv[1]))
rendered = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else {}
pages = [p for p in crawl["pages"] if not p["path"].startswith("/images/")]
ok = [p for p in pages if p["status"] == 200]

df = collections.Counter()
for p in ok:
    for line in set(p.get("mainLines", [])):
        df[line] += 1
for p in ok:
    p["uniqueWords"] = sum(len(l.split()) for l in p.get("mainLines", []) if df[l] <= BOILERPLATE_PAGES)

def indexable(p):
    return p["status"] == 200 and not (p.get("robots") and "noindex" in p["robots"])

def login(p):
    return p["status"] in (302, 303, 307, 308) and "/signin" in (p.get("location") or "")

idx = [p for p in ok if indexable(p)]
titles = collections.Counter(p["title"] for p in idx)
descs = collections.Counter(p.get("description") for p in idx)

def flags(p):
    f = []
    if p["status"] != 200:
        f.append(f"HTTP {p['status']}" + (" → sign-in" if login(p) else ""))
        return f
    if p["uniqueWords"] < THIN:
        f.append(f"<{THIN} unique words")
    if p.get("placeholderHits"):
        f.append("placeholder language: " + ", ".join(p["placeholderHits"]))
    if indexable(p) and titles[p["title"]] > 1:
        f.append("duplicate title")
    if indexable(p) and descs[p.get("description")] > 1:
        f.append("duplicate description")
    if p["path"] != "/" and p.get("ogTitle") == DEFAULT_TITLE:
        f.append("og:title is the home page's")
    elif p.get("ogTitle") and p.get("title") and p["ogTitle"] != p["title"]:
        f.append("og:title ≠ title")
    if p.get("ogDescription") and p.get("description") and p["ogDescription"] != p["description"]:
        f.append("og:description ≠ description")
    if (p.get("title") or "") and len(p["title"]) > 60:
        f.append(f"title {len(p['title'])} chars")
    d = p.get("description") or ""
    if not (120 <= len(d) <= 160):
        f.append(f"description {len(d)} chars")
    if re.search(r"[A-Z]", p["path"]):
        f.append("mixed-case URL")
    r = rendered.get(p["path"])
    if r is not None and r > 1.5 * p["mainWords"] + 100:
        f.append(f"content added by JS (raw {p['mainWords']} → rendered {r} words)")
    if p.get("adMarkers"):
        f.append(f"{p['adMarkers']} ad element(s)")
    return f

out = []
w = out.append
w("# AUDIT — public routes\n")
w(f"> Generated by `scripts/audit-report.py` from a crawl of `{crawl['base']}` "
  f"(`scripts/audit-crawl.py`: from `/` and every sitemap URL, following internal links, no JavaScript). "
  f"Words are counted in the server-rendered HTML. **Unique words** exclude every text line that "
  f"appears on more than {BOILERPLATE_PAGES} pages. Rendered counts: headless Chrome at 1440 px, "
  f"`<main>` innerText.\n")
w("## Summary\n")
w("| Measure | Count |\n| --- | --- |")
w(f"| Routes reached | {len(pages)} |")
w(f"| HTTP 200 | {len(ok)} |")
w(f"| Behind sign-in (redirect to /signin) | {sum(1 for p in pages if login(p))} |")
w(f"| Indexable (200, not noindexed) | {len(idx)} |")
w(f"| Indexable with < {THIN} unique words | {sum(1 for p in idx if p['uniqueWords'] < THIN)} |")
w(f"| Pages with placeholder / unfinished language | {sum(1 for p in ok if p.get('placeholderHits'))} |")
w(f"| Indexable pages sharing a title | {sum(c for t, c in titles.items() if c > 1)} |")
w(f"| Indexable pages sharing a description | {sum(c for d, c in descs.items() if c > 1)} |")
w(f"| og:title equal to the home page's (not on `/`) | {sum(1 for p in ok if p['path'] != '/' and p.get('ogTitle') == DEFAULT_TITLE)} |")
w(f"| Mixed-case URLs | {sum(1 for p in pages if re.search(r'[A-Z]', p['path']))} |")
w(f"| Pages whose main content appears only after JavaScript | {sum(1 for p in ok if rendered.get(p['path']) is not None and rendered[p['path']] > 1.5 * p['mainWords'] + 100)} |")
w(f"| Pages with ad elements in the HTML | {sum(1 for p in ok if p.get('adMarkers'))} |")
w(f"| Pages missing the AdSense loader / meta | {sum(1 for p in ok if not p.get('adsLoader'))} / {sum(1 for p in ok if not p.get('adsMeta'))} |")
w("")
w("## Every route\n")
w("| Route | Status | Index | Unique words | Main words | Rendered | Title | Description (chars) | og:title | Flags |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for p in sorted(pages, key=lambda x: x["path"]):
    ogt = "home's" if (p["path"] != "/" and p.get("ogTitle") == DEFAULT_TITLE) else ("= title" if p.get("ogTitle") == p.get("title") else (p.get("ogTitle") or "—"))
    w(f"| `{p['path']}` | {p['status']} | {'yes' if indexable(p) else 'no'} | {p.get('uniqueWords', '')} | {p.get('mainWords', '')} | "
      f"{rendered.get(p['path'], '')} | {(p.get('title') or '').replace('|', '·')[:70]} | {len(p.get('description') or '')} | "
      f"{ogt.replace('|', '·')[:40]} | {'; '.join(flags(p)) or '—'} |")
w("")
w("## Duplicate titles and descriptions among indexable pages\n")
for t, c in titles.items():
    if c > 1:
        w(f"- Title ×{c}: “{t}” — " + ", ".join(f"`{p['path']}`" for p in idx if p["title"] == t))
for d, c in descs.items():
    if c > 1:
        w(f"- Description ×{c}: “{(d or '')[:90]}…” — " + ", ".join(f"`{p['path']}`" for p in idx if p.get("description") == d))
w("")
w("## Placeholder or unfinished language\n")
for p in ok:
    if p.get("placeholderHits"):
        w(f"- `{p['path']}`: {', '.join(p['placeholderHits'])}")
w("")
print("\n".join(out))
